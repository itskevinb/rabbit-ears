"""Make rf-tv/picture.h: a 320x240 greyscale image for the ESP32 TV transmitter.

    python3 tools/make_image.py            # built-in test card
    python3 tools/make_image.py photo.jpg  # any picture, cropped to 4:3
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageOps

W, H = 320, 240
OUT = Path(__file__).resolve().parent.parent / "rf-tv" / "picture.h"


def test_card():
    img = Image.new("L", (W, H), 200)
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, W - 1, H - 1], outline=0, width=8)
    for i in range(8):  # grey staircase, black to white
        x0 = 20 + i * 35
        d.rectangle([x0, 18, x0 + 35, 58], fill=int(i * 255 / 7))
    d.ellipse([90, 66, 230, 206], fill=255, outline=0, width=6)
    d.line([160, 66, 160, 206], fill=0, width=4)
    d.line([90, 136, 230, 136], fill=0, width=4)
    font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 44, index=1)
    d.text((W // 2, 136), "HELLO", font=font, fill=0, anchor="mm",
           stroke_width=2, stroke_fill=255)
    small = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 22, index=1)
    d.text((W // 2, 222), "ESP32 CHANNEL 4", font=small, fill=0, anchor="mm")
    return img


def photo(path):
    img = ImageOps.exif_transpose(Image.open(path)).convert("L")
    return ImageOps.autocontrast(ImageOps.fit(img, (W, H)), cutoff=1)


img = photo(sys.argv[1]) if len(sys.argv) > 1 else test_card()
img.save(OUT.with_suffix(".png"))
px = img.tobytes()
rows = ",\n".join(", ".join(str(b) for b in px[i:i + 32]) for i in range(0, len(px), 32))
OUT.write_text(f"// Generated by tools/make_image.py. 0 = black, 255 = white.\n"
               f"#pragma once\nconst int PIC_W = {W}, PIC_H = {H};\n"
               f"const uint8_t PICTURE[{W * H}] = {{\n{rows}\n}};\n")
print(f"wrote {OUT}")
